import esbuild from "esbuild";
import process from "process";
// 4-3: API nativa (Node >= 16). El conjunto es un superconjunto
// del antiguo paquete builtin-modules: ningún módulo del paquete
// falta, por lo que la lista de externals cubre lo mismo o más.
import { builtinModules } from "node:module";
import { readFileSync } from "fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";

// Plugin para empaquetar JSON y MD como recursos
const resourcePlugin = {
  name: 'resource-loader',
  setup(build) {
    // Cargar archivos .json como objetos JavaScript
    build.onLoad({ filter: /\.json$/ }, async (args) => {
      const content = readFileSync(args.path, 'utf8');
      return {
        contents: `module.exports = ${content}`,
        loader: 'js'
      };
    });

    // Cargar archivos .md como strings
    build.onLoad({ filter: /\.md$/ }, async (args) => {
      const content = readFileSync(args.path, 'utf8');
      return {
        contents: `module.exports = ${JSON.stringify(content)}`,
        loader: 'js'
      };
    });
  }
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "./src/main.js",
  plugins: [resourcePlugin],  // Añadir el plugin
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
